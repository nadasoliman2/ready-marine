export const chatCopy = (language) => (language === 'en' ? COPY.en : COPY.ar);

export function formatMoney(value, language) {
    if (value === null || value === undefined || !Number.isFinite(Number(value))) return '';
    const n = Number(value);
    // Western digits in both languages, like every price on the storefront.
    const text = n.toLocaleString('en-US', { maximumFractionDigits: n % 1 ? 2 : 0 });
    return `${text} ${chatCopy(language).currency}`;
}
